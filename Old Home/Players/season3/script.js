function showToast(message, type = "success") {
  const toast = document.getElementById("toast");
  toast.textContent = message;
  toast.className = `toast is-visible ${type === "error" ? "is-error" : ""}`;
  window.clearTimeout(showToast.timer);
  showToast.timer = window.setTimeout(() => {
    toast.className = "toast";
  }, 3200);
}

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, (character) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
  }[character]));
}

function getVisibleStats(player) {
  return Object.entries(player.stats).filter(([key]) => key !== "Position");
}

function renderStatRows(player) {
  return getVisibleStats(player).map(([key, value]) => {
    const label = key === "MOTM" ? "Man of the Match" : key;
    const icon = {
      "Appearances": "◎",
      "Goals": "⚽",
      "Assists": "↗",
      "Yellow Cards": "▰",
      "Red Cards": "▰",
      "Penalty Saves": "🥅",
      "Clean Sheets": "✦",
    }[key] || "•";
    return `
      <div class="stat-row">
        <span class="stat-label"><span class="stat-icon" aria-hidden="true">${icon}</span>${escapeHtml(label)}</span>
        <strong class="stat-value">${Number(value) || 0}</strong>
      </div>`;
  }).join("");
}

